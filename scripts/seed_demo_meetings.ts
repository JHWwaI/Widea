async function main() {
  console.log("🌱 루프 데모 회의록 시드 시작...\n");

  // 기존 데모 데이터 중복 방지 — 같은 title이면 skip
  for (const m of MEETINGS) {
    const existing = await prisma.meetingNote.findFirst({
      where: { userId: USER_ID, ideaId: IDEA_ID, title: m.title },
    });
    if (existing) {
      console.log(`⏭  스킵 (이미 존재): ${m.title}`);
      continue;
    }

    await prisma.meetingNote.create({
      data: {
        userId: USER_ID,
        ideaId: IDEA_ID,
        title: m.title,
        source: m.source,
        templateKey: m.templateKey,
        durationSec: m.durationSec,
        transcriptText: m.transcriptText,
        summary: m.summary as object,
        createdAt: m.createdAt,
      },
    });

    console.log(`✅ 생성: ${m.title} (${m.templateKey})`);
  }

  console.log("\n🎉 완료!");
}

